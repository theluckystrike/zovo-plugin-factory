/* G-code Viewer Online (TOOLCHK, wave18; first draft by HTOOL3, rewritten). Plain JavaScript, no library, no request.
   Reads 3D printer and CNC G-code in this tab: modal G0 to G3 with arcs (I, J or R, XY plane), G20/G21, G90/G91,
   M82/M83, G92 (axes and E), G28, G4, temperatures, tools and the slicer's ;TYPE: or ; FEATURE: comments. Moves are
   kept in typed arrays and drawn on a canvas (top or front view) one color batch at a time, so big files stay usable.
   File text is shown with textContent, never as HTML. */
'use strict';
(() => {
  const $ = id => document.getElementById(id);
  let M = null, lines = null;
  const V = { view: 'top', scale: 1, ox: 0, oy: 0, layer: 0, one: false, travel: false, color: 'feature', sel: -1 };

  /* ---------------- parser ---------------- */
  const FEAT = [['Outer wall', /outer|external perimeter|wall-outer|perimeter.*external/i, '#e5484d'], ['Inner wall', /inner|perimeter|wall/i, '#f08c00'],
    ['Infill', /sparse|internal infill|^fill$|infill/i, '#2fa14a'], ['Top and bottom skin', /skin|solid|top|bottom|ironing/i, '#a35ad6'],
    ['Skirt and brim', /skirt|brim/i, '#1d9a8a'], ['Support', /support/i, '#d6a20b'], ['Bridge', /bridge/i, '#3a7bd5'], ['Other', /./, '#8a94a3']];
  function featIndex(name) { for (let i = 0; i < FEAT.length; i++) if (FEAT[i][1].test(name)) return i; return FEAT.length - 1; }

  function parse(text) {
    let cap = 1 << 16, n = 0;
    let A = { x0: new Float32Array(cap), y0: new Float32Array(cap), z0: new Float32Array(cap), x1: new Float32Array(cap), y1: new Float32Array(cap), z1: new Float32Array(cap),
      kind: new Uint8Array(cap), feat: new Uint8Array(cap), feed: new Float32Array(cap), layer: new Uint32Array(cap), line: new Uint32Array(cap), tool: new Uint8Array(cap) };
    const grow = () => { cap *= 2; for (const k in A) { const b = new A[k].constructor(cap); b.set(A[k]); A[k] = b; } };
    const st = { abs: true, absE: true, mm: 1, motion: 0, feed: 0, plane: 17, tool: 0 };
    const pos = { x: 0, y: 0, z: 0 }, off = { x: 0, y: 0, z: 0 };
    let e = 0, feat = FEAT.length - 1, layerMarks = 0, curLayerMark = -1;
    const S = { filament: 0, retracts: 0, printLen: 0, travelLen: 0, cutLen: 0, time: 0, dwell: 0, arcs: 0, tempT: null, tempB: null, spindle: null, tools: new Set(), slicer: null, slicerTime: null, feeds: [Infinity, 0], extrudes: 0, lines: 0, gWords: 0 };
    let lineNo = 0, p = 0;
    const L = text.length;
    const add = (x0, y0, z0, x1, y1, z1, kind, f) => {
      if (n === cap) grow();
      A.x0[n] = x0; A.y0[n] = y0; A.z0[n] = z0; A.x1[n] = x1; A.y1[n] = y1; A.z1[n] = z1; A.kind[n] = kind; A.feat[n] = feat; A.feed[n] = f; A.layer[n] = curLayerMark; A.line[n] = lineNo; A.tool[n] = st.tool; n++;
    };
    while (p < L) {
      let q = text.indexOf('\n', p); if (q < 0) q = L;
      lineNo++;
      let s = text.slice(p, q); p = q + 1;
      // comments: ';' to the end, '( ... )' anywhere; slicer facts live in them
      const sc = s.indexOf(';');
      let com = '';
      if (sc >= 0) { com = s.slice(sc + 1).trim(); s = s.slice(0, sc); }
      if (s.indexOf('(') >= 0) { const m = s.match(/\(([^)]*)\)/); if (m && !com) com = m[1].trim(); s = s.replace(/\([^)]*\)/g, ''); }
      if (com) {
        let m;
        if ((m = /^(?:TYPE|FEATURE)\s*:\s*(.+)$/i.exec(com))) feat = featIndex(m[1]);
        else if (/^LAYER:\s*-?\d+|^LAYER_CHANGE|^CHANGE_LAYER|^layer num\/total_layer_count/i.test(com)) { layerMarks++; curLayerMark = layerMarks - 1; }
        else if ((m = /^TIME:\s*(\d+(?:\.\d+)?)/i.exec(com))) S.slicerTime = +m[1];
        else if ((m = /(?:estimated printing time(?: \(normal mode\))?|total estimated time|model printing time)\s*[:=]\s*(.+)$/i.exec(com)) && S.slicerTime == null) {
          let t = 0; const r = /(\d+(?:\.\d+)?)\s*([dhms])/g; let x;
          while ((x = r.exec(m[1]))) t += +x[1] * { d: 86400, h: 3600, m: 60, s: 1 }[x[2]];
          if (t) S.slicerTime = t;
        } else if ((m = /^(?:Generated with|generated by|Cura_SteamEngine|PrusaSlicer|OrcaSlicer|BambuStudio|SuperSlicer|Simplify3D)\s*[:=]?\s*(.*)$/i.exec(com)) && !S.slicer) S.slicer = com.replace(/^generated (with|by)\s*/i, '').replace(/^BambuStudio/, 'Bambu Studio').slice(0, 80);
      }
      s = s.trim();
      if (!s) continue;
      // words: letter + number; N line numbers and *checksums are dropped
      const W = {}; let g = -1, mcode = -1;
      const re = /([A-Za-z])\s*([-+]?(?:\d+\.?\d*|\.\d+))/g; let w;
      while ((w = re.exec(s))) {
        const k = w[1].toUpperCase(), v = +w[2];
        if (k === 'G') { const gi = Math.round(v * 10) / 10; if (gi <= 3) { st.motion = gi; g = gi; } else g = gi; handleG(gi); }
        else if (k === 'M') mcode = v;
        else if (k === 'T') { st.tool = Math.min(255, v | 0); S.tools.add('T' + (v | 0)); }
        else if (k !== 'N' && k !== '*') W[k] = v;
      }
      function handleG(gi) {
        if (gi === 20) st.mm = 25.4; else if (gi === 21) st.mm = 1; else if (gi === 90) { st.abs = true; st.absE = true; } else if (gi === 91) { st.abs = false; st.absE = false; }  // Marlin: G90/G91 set E too, M82/M83 after them win
        else if (gi === 17 || gi === 18 || gi === 19) st.plane = gi;
      }
      if (mcode >= 0) {
        if (mcode === 82) st.absE = true; else if (mcode === 83) st.absE = false;
        else if ((mcode === 104 || mcode === 109) && W.S > 0) S.tempT = W.S;
        else if ((mcode === 140 || mcode === 190) && W.S > 0) S.tempB = W.S;
        else if ((mcode === 3 || mcode === 4) && W.S > 0) S.spindle = W.S;
        if (mcode !== 3 && mcode !== 4) continue;
      }
      if (g === 92) {  // set position: the machine does not move, the numbers do
        for (const a of ['x', 'y', 'z']) if (W[a.toUpperCase()] != null) off[a] = pos[a] - W[a.toUpperCase()] * st.mm;
        if (W.E != null) e = W.E * st.mm;
        if (W.X == null && W.Y == null && W.Z == null && W.E == null) { off.x = pos.x; off.y = pos.y; off.z = pos.z; e = 0; }
        continue;
      }
      if (g === 28) { const all = W.X == null && W.Y == null && W.Z == null; for (const a of ['x', 'y', 'z']) if (all || W[a.toUpperCase()] != null) { pos[a] = 0; off[a] = 0; } continue; }
      if (g === 4) { S.dwell += W.P != null ? W.P / 1000 : W.S != null ? W.S : 0; continue; }
      if (g > 3 && g !== -1) continue;
      if (W.F != null) st.feed = W.F * st.mm;
      if (W.X == null && W.Y == null && W.Z == null && W.E == null) continue;
      if (g === -1 && st.motion > 3) continue;
      S.gWords++;
      const mot = st.motion;
      const tx = W.X == null ? pos.x : st.abs ? W.X * st.mm + off.x : pos.x + W.X * st.mm;
      const ty = W.Y == null ? pos.y : st.abs ? W.Y * st.mm + off.y : pos.y + W.Y * st.mm;
      const tz = W.Z == null ? pos.z : st.abs ? W.Z * st.mm + off.z : pos.z + W.Z * st.mm;
      let de = 0;
      if (W.E != null) { const ev = W.E * st.mm; de = st.absE ? ev - e : ev; e = st.absE ? ev : e + ev; }
      S.filament += de;  // net E: an unretract gives back what its retraction took, so it is not counted twice
      if (de > 0) S.extrudes++; else if (de < 0) S.retracts++;
      const kind = mot === 0 ? 0 : de > 0 ? 1 : 2;  // 0 travel or rapid, 1 extrusion, 2 move without extrusion (a CNC cut)
      const f = mot === 0 ? (st.feed || 5000) : st.feed;
      if (f > 0 && mot !== 0) { if (f < S.feeds[0]) S.feeds[0] = f; if (f > S.feeds[1]) S.feeds[1] = f; }
      if ((mot === 2 || mot === 3) && st.plane === 17 && (W.I != null || W.J != null || W.R != null)) {
        S.arcs++;
        let cx, cy;
        if (W.R != null) {
          const r = W.R * st.mm, dx = tx - pos.x, dy = ty - pos.y, d = Math.hypot(dx, dy);
          const h = Math.sqrt(Math.max(0, r * r - d * d / 4)) * ((mot === 2) === (r > 0) ? -1 : 1);
          cx = pos.x + dx / 2 - h * dy / (d || 1); cy = pos.y + dy / 2 + h * dx / (d || 1);
        } else { cx = pos.x + (W.I || 0) * st.mm; cy = pos.y + (W.J || 0) * st.mm; }
        const r = Math.hypot(pos.x - cx, pos.y - cy);
        let a0 = Math.atan2(pos.y - cy, pos.x - cx), a1 = Math.atan2(ty - cy, tx - cx);
        if (mot === 2) { if (a1 >= a0 - 1e-9) a1 -= 2 * Math.PI; } else if (a1 <= a0 + 1e-9) a1 += 2 * Math.PI;
        const span = a1 - a0, segs = Math.max(2, Math.min(128, Math.ceil(Math.abs(span) * Math.max(r, 1) / 1.5)));
        let px = pos.x, py = pos.y, pz = pos.z;
        for (let i = 1; i <= segs; i++) {
          const a = a0 + span * i / segs, nx = i === segs ? tx : cx + r * Math.cos(a), ny = i === segs ? ty : cy + r * Math.sin(a), nz = pos.z + (tz - pos.z) * i / segs;
          add(px, py, pz, nx, ny, nz, kind, f); px = nx; py = ny; pz = nz;
        }
        const len = Math.abs(span) * r; S.time += f > 0 ? len / f * 60 : 0;
        if (kind === 1) S.printLen += len; else if (kind === 2) S.cutLen += len; else S.travelLen += len;
      } else {
        const len = Math.hypot(tx - pos.x, ty - pos.y, tz - pos.z) || Math.abs(de);
        add(pos.x, pos.y, pos.z, tx, ty, tz, kind, f);
        S.time += f > 0 ? len / f * 60 : 0;
        if (kind === 1) S.printLen += len; else if (kind === 2) S.cutLen += len; else S.travelLen += len;
      }
      pos.x = tx; pos.y = ty; pos.z = tz;
    }
    S.lines = lineNo;
    const print = S.extrudes > 0;
    if (print) { for (let i = 0; i < n; i++) if (A.kind[i] === 2) A.kind[i] = 0; S.travelLen += S.cutLen; S.cutLen = 0; }  // a printer move without extrusion is travel
    // layers: slicer comments when there are any, else Z changes of extrusions (print) or cuts (CNC)
    const layer = new Uint32Array(n), zs = [];
    if (print && layerMarks > 1) {
      let maxL = 0;
      for (let i = 0; i < n; i++) { layer[i] = A.layer[i] === 0xffffffff ? 0 : A.layer[i]; if (layer[i] > maxL) maxL = layer[i]; }
      for (let l = 0; l <= maxL; l++) zs.push(null);
      for (let i = 0; i < n; i++) if (A.kind[i] === 1 && zs[layer[i]] == null) zs[layer[i]] = A.z1[i];
    } else {
      const work = print ? 1 : 2;
      let cur = -1, lastZ = Infinity;
      for (let i = 0; i < n; i++) {
        if (A.kind[i] === work && Math.abs(A.z1[i] - lastZ) > 1e-4 && Math.abs(A.z1[i] - A.z0[i]) < 1e-4) { cur++; lastZ = A.z1[i]; zs.push(lastZ); }
        layer[i] = Math.max(0, cur);
      }
    }
    if (!zs.length) zs.push(0);
    const bb = [Infinity, Infinity, Infinity, -Infinity, -Infinity, -Infinity];
    for (let i = 0; i < n; i++) if (A.kind[i] !== 0) { for (const [x, y, z] of [[A.x0[i], A.y0[i], A.z0[i]], [A.x1[i], A.y1[i], A.z1[i]]]) { if (x < bb[0]) bb[0] = x; if (y < bb[1]) bb[1] = y; if (z < bb[2]) bb[2] = z; if (x > bb[3]) bb[3] = x; if (y > bb[4]) bb[4] = y; if (z > bb[5]) bb[5] = z; } }
    if (!isFinite(bb[0])) for (let i = 0; i < n; i++) { const x = A.x1[i], y = A.y1[i], z = A.z1[i]; if (x < bb[0]) bb[0] = x; if (y < bb[1]) bb[1] = y; if (z < bb[2]) bb[2] = z; if (x > bb[3]) bb[3] = x; if (y > bb[4]) bb[4] = y; if (z > bb[5]) bb[5] = z; }
    S.time += S.dwell;
    return { A, n, layer, zs, nl: zs.length, bb, S, print };
  }

  /* ---------------- drawing ---------------- */
  const cv = $('gcv'), ctx = cv.getContext('2d');
  const SPEED = ['#3b4cc0', '#5a78d6', '#7f9fe6', '#a9c1f0', '#d3dbe6', '#eec7b0', '#eaa281', '#dd7a5c', '#c94f3f', '#b40426'];
  const LAYERC = ['#3a7bd5', '#2fa14a', '#e08a1e', '#a35ad6', '#e5484d', '#1d9a8a'];
  function fitView() {
    const w = cv.clientWidth, h = cv.clientHeight, b = M.bb;
    const [ax, ay, bx, by] = V.view === 'top' ? [b[0], b[1], b[3], b[4]] : [b[0], b[2], b[3], b[5]];
    const sw = Math.max(bx - ax, 1), sh = Math.max(by - ay, 1);
    V.scale = Math.min((w - 40) / sw, (h - 40) / sh);
    V.ox = w / 2 - (ax + bx) / 2 * V.scale; V.oy = h / 2 + (ay + by) / 2 * V.scale;
  }
  const sx = x => V.ox + x * V.scale, sy = y => V.oy - y * V.scale;
  function bucket(i) {
    const A = M.A, k = A.kind[i];
    if (k === 0) return ['Travel' + (M.print ? '' : ' (rapid)'), M.print ? '#8a94a3' : '#e5484d'];
    if (V.color === 'feature') return M.print ? [FEAT[A.feat[i]][0], FEAT[A.feat[i]][2]] : [A.z1[i] !== A.z0[i] && A.x0[i] === A.x1[i] && A.y0[i] === A.y1[i] ? 'Plunge' : 'Cut', A.z1[i] !== A.z0[i] && A.x0[i] === A.x1[i] && A.y0[i] === A.y1[i] ? '#d6a20b' : '#2fa14a'];
    if (V.color === 'speed') { const [lo, hi] = M.S.feeds, t = hi > lo ? Math.min(.9999, Math.max(0, (A.feed[i] - lo) / (hi - lo))) : .5, j = Math.floor(t * 10); return [Math.round(lo + (hi - lo) * j / 10) / 60 + ' mm/s and up', SPEED[j]]; }
    if (V.color === 'tool') return ['T' + A.tool[i], LAYERC[A.tool[i] % LAYERC.length]];
    const l = M.layer[i]; return [(M.print ? 'Layer ' : 'Z pass ') + (l + 1) + ' (repeats every 6)', LAYERC[l % LAYERC.length]];
  }
  function draw() {
    if (!M) return;
    const dpr = devicePixelRatio || 1, w = cv.clientWidth, h = cv.clientHeight;
    if (cv.width !== Math.round(w * dpr)) { cv.width = Math.round(w * dpr); cv.height = Math.round(h * dpr); }
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0); ctx.clearRect(0, 0, w, h);
    const A = M.A, top = V.view === 'top', paths = new Map(), dim = new Path2D();
    let dimN = 0;
    for (let i = 0; i < M.n; i++) {
      const l = M.layer[i];
      if (l > V.layer || (V.one && l !== V.layer)) continue;
      if (A.kind[i] === 0 && !V.travel) continue;
      const x0 = sx(A.x0[i]), y0 = sy(top ? A.y0[i] : A.z0[i]), x1 = sx(A.x1[i]), y1 = sy(top ? A.y1[i] : A.z1[i]);
      if (top && !V.one && l < V.layer && A.kind[i] !== 0) { dim.moveTo(x0, y0); dim.lineTo(x1, y1); dimN++; continue; }
      const [name, col] = bucket(i);
      let p = paths.get(name);
      if (!p) { p = [new Path2D(), col]; paths.set(name, p); }
      p[0].moveTo(x0, y0); p[0].lineTo(x1, y1);
    }
    ctx.lineCap = 'round';
    if (dimN) { ctx.strokeStyle = getComputedStyle(document.documentElement).getPropertyValue('--mut'); ctx.globalAlpha = .28; ctx.lineWidth = 1; ctx.stroke(dim); ctx.globalAlpha = 1; }
    ctx.lineWidth = Math.max(1, Math.min(3, V.scale * .4));
    for (const [name, [p, col]] of paths) { ctx.strokeStyle = col; ctx.globalAlpha = name.startsWith('Travel') ? .55 : 1; ctx.lineWidth = name.startsWith('Travel') ? 1 : Math.max(1, Math.min(3, V.scale * .4)); ctx.stroke(p); }
    ctx.globalAlpha = 1;
    if (V.sel >= 0) { const i = V.sel; ctx.strokeStyle = '#ff2fd6'; ctx.lineWidth = 4; ctx.beginPath(); ctx.moveTo(sx(A.x0[i]), sy(top ? A.y0[i] : A.z0[i])); ctx.lineTo(sx(A.x1[i]), sy(top ? A.y1[i] : A.z1[i])); ctx.stroke(); }
    const lg = $('legend'); lg.textContent = '';
    if (dimN) paths.set('Layers below', [null, 'var(--mut)']);
    for (const [name, [, col]] of [...paths].sort((a, b) => a[0].localeCompare(b[0], 'en', { numeric: true }))) {
      if (V.color === 'layer' && /^(Layer|Z pass)/.test(name) && lg.childElementCount > 12) continue;
      const s = document.createElement('span'), sw = document.createElement('i'); sw.style.background = col; s.append(sw, name.replace(' (repeats every 6)', '')); lg.append(s);
    }
    const z = M.zs[V.layer];
    $('layerTxt').textContent = (M.print ? 'Layer ' : 'Z pass ') + (V.layer + 1) + ' of ' + M.nl + (z != null ? ', Z ' + (+z.toFixed(3)) + ' mm' : '');
  }

  /* ---------------- stats ---------------- */
  const tfmt = s => { s = Math.round(s); const h = Math.floor(s / 3600), m = Math.floor(s % 3600 / 60); return (h ? h + ' h ' : '') + m + ' min ' + (h ? '' : s % 60 + ' s'); };
  const mm = v => +v.toFixed(2) + ' mm';
  function stats() {
    const S = M.S, b = M.bb, dia = +$('dia').value || 1.75, den = +$('den').value || 1.24;
    const grams = Math.PI * (dia / 2) ** 2 * S.filament / 1000 * den;
    const rows = M.print ? [
      ['Mode', '3D print (the file extrudes)'], ['Layers', M.nl.toLocaleString('en-US')], ['Size X x Y x Z', mm(b[3] - b[0]) + ' x ' + mm(b[4] - b[1]) + ' x ' + mm(b[5] - b[2])],
      ['Print time (from feed rates)', tfmt(S.time) + ', no acceleration, so real prints take a little longer'], ['Slicer estimate', S.slicerTime != null ? tfmt(S.slicerTime) : 'not in the file'],
      ['Filament', (S.filament / 1000).toFixed(2) + ' m, ' + grams.toFixed(1) + ' g'], ['Retractions', S.retracts.toLocaleString('en-US')],
      ['Speed range', isFinite(S.feeds[0]) ? Math.round(S.feeds[0] / 60) + ' to ' + Math.round(S.feeds[1] / 60) + ' mm/s' : ''],
      ['Nozzle and bed', (S.tempT != null ? S.tempT + ' °C' : '?') + ' and ' + (S.tempB != null ? S.tempB + ' °C' : '?')]]
      : [['Mode', 'CNC (no extrusion in the file)'], ['Z passes', M.nl.toLocaleString('en-US')], ['Size X x Y x Z', mm(b[3] - b[0]) + ' x ' + mm(b[4] - b[1]) + ' x ' + mm(b[5] - b[2])],
        ['Cycle time (from feed rates)', tfmt(S.time) + ', rapids at 5000 mm/min unless the file sets F'], ['Cut length', mm(S.cutLen)], ['Rapid length', mm(S.travelLen)],
        ['Feed range', isFinite(S.feeds[0]) ? Math.round(S.feeds[0]) + ' to ' + Math.round(S.feeds[1]) + ' mm/min' : ''], ['Tools', [...S.tools].join(', ') || 'none named'], ['Spindle', S.spindle != null ? S.spindle + ' rpm' : 'not set']];
    rows.push(['Lines, moves, arcs', S.lines.toLocaleString('en-US') + ', ' + M.n.toLocaleString('en-US') + ' drawn segments, ' + S.arcs.toLocaleString('en-US') + ' arcs']);
    if (S.slicer) rows.push(['Made by', S.slicer]);
    $('gstats').innerHTML = rows.filter(r => r[1]).map(([k, v]) => `<tr><th>${esc(k)}</th><td>${esc(v)}</td></tr>`).join('');
    $('weightBox').hidden = !M.print;
  }
  const esc = s => String(s == null ? '' : s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

  /* ---------------- open ---------------- */
  self.zovoOpen = async file => {
    if (file.size > 500 * 1048576) throw new Error('it is ' + self.zovoSize(file.size) + '. This page opens G-code files up to 500 MB.');
    const text = await file.text();
    if (/^GCDE/.test(text.slice(0, 4))) throw new Error('it is binary G-code (.bgcode). Export plain G-code from PrusaSlicer to view it here.');
    if (/^CDF\x01|^CDF\x02|^\x89HDF/.test(text.slice(0, 8))) throw new Error('it is a NetCDF data file, not G-code. Open it in the HDF5 and NetCDF viewer.');
    M = parse(text);
    if (!M.n) throw new Error('no G0, G1, G2 or G3 move was found, so it is not G-code.');
    lines = text;
    Object.assign(V, { layer: M.nl - 1, one: false, travel: !M.print, sel: -1, color: 'feature' });
    $('gcolor').innerHTML = M.print ? '<option value="feature">Feature</option><option value="speed">Speed</option><option value="layer">Layer</option><option value="tool">Tool</option>'
      : '<option value="feature">Move type</option><option value="speed">Feed rate</option><option value="layer">Z pass</option><option value="tool">Tool</option>';
    $('travel').checked = V.travel; $('travelLbl').textContent = M.print ? 'Travel' : 'Rapids';
    $('one').checked = false;
    $('lslider').max = M.nl - 1; $('lslider').value = M.nl - 1;
    $('fmeta').textContent = self.zovoSize(file.size);
    stats(); fitView(); draw();
    return 'Opened ' + file.name + ' in ' + (M.print ? '3D print' : 'CNC') + ' mode: ' + M.nl.toLocaleString('en-US') + (M.print ? ' layers.' : ' Z passes.');
  };

  /* ---------------- input ---------------- */
  $('lslider').addEventListener('input', () => { V.layer = +$('lslider').value; V.sel = -1; draw(); });
  $('one').addEventListener('change', () => { V.one = $('one').checked; draw(); });
  $('travel').addEventListener('change', () => { V.travel = $('travel').checked; draw(); });
  $('gcolor').addEventListener('change', () => { V.color = $('gcolor').value; draw(); });
  $('gview').addEventListener('change', () => { V.view = $('gview').value; fitView(); draw(); });
  $('gfit').addEventListener('click', () => { if (M) { fitView(); draw(); } });
  for (const id of ['dia', 'den']) $(id).addEventListener('input', () => M && stats());
  cv.addEventListener('wheel', e => {
    if (!M) return; e.preventDefault();
    const r = cv.getBoundingClientRect(), x = e.clientX - r.left, y = e.clientY - r.top, f = Math.exp(-e.deltaY * .0015);
    V.ox = x - (x - V.ox) * f; V.oy = y - (y - V.oy) * f; V.scale *= f; draw();
  }, { passive: false });
  let drag = null;
  cv.addEventListener('pointerdown', e => { if (M) { drag = { x: e.clientX, y: e.clientY, ox: V.ox, oy: V.oy, moved: false }; cv.setPointerCapture(e.pointerId); } });
  cv.addEventListener('pointermove', e => { if (!drag) return; const dx = e.clientX - drag.x, dy = e.clientY - drag.y; if (Math.abs(dx) + Math.abs(dy) > 3) drag.moved = true; if (drag.moved) { V.ox = drag.ox + dx; V.oy = drag.oy + dy; draw(); } });
  cv.addEventListener('pointerup', e => {
    if (!drag) return; const moved = drag.moved; drag = null; if (moved) return;
    // pick the nearest shown move within 8 px and show its line of G-code
    const r = cv.getBoundingClientRect(), px = e.clientX - r.left, py = e.clientY - r.top, A = M.A, top = V.view === 'top';
    let best = -1, bd = 64;
    for (let i = 0; i < M.n; i++) {
      const l = M.layer[i];
      if (l > V.layer || (V.one && l !== V.layer) || (top && !V.one && l < V.layer && A.kind[i] !== 0) || (A.kind[i] === 0 && !V.travel)) continue;
      const x0 = sx(A.x0[i]), y0 = sy(top ? A.y0[i] : A.z0[i]), x1 = sx(A.x1[i]), y1 = sy(top ? A.y1[i] : A.z1[i]);
      const dx = x1 - x0, dy = y1 - y0, t = Math.max(0, Math.min(1, ((px - x0) * dx + (py - y0) * dy) / (dx * dx + dy * dy || 1)));
      const d = (x0 + t * dx - px) ** 2 + (y0 + t * dy - py) ** 2;
      if (d < bd) { bd = d; best = i; }
    }
    V.sel = best; draw();
    if (best < 0) { $('lineBox').textContent = ''; return; }
    const ln = A.line[best];
    let p = 0; for (let k = 1; k < ln && p >= 0; k++) p = lines.indexOf('\n', p) + 1;
    const end = lines.indexOf('\n', p);
    $('lineBox').textContent = 'Line ' + ln.toLocaleString('en-US') + ': ' + lines.slice(p, end < 0 ? undefined : end).trim().slice(0, 300) + (M.print ? '   (' + FEAT[A.feat[best]][0] + ', layer ' + (M.layer[best] + 1) + ')' : '');
  });
  addEventListener('keydown', e => {
    if (!M || /^(INPUT|SELECT|TEXTAREA)$/.test(document.activeElement.tagName)) return;
    if (e.key === 'ArrowUp' || e.key === 'ArrowDown') { e.preventDefault(); V.layer = Math.max(0, Math.min(M.nl - 1, V.layer + (e.key === 'ArrowUp' ? 1 : -1))); }
    else if (e.key === 'Home') V.layer = 0; else if (e.key === 'End') V.layer = M.nl - 1;
    else if (e.key === 's' || e.key === 'S') { V.one = !V.one; $('one').checked = V.one; }
    else if (e.key === 't' || e.key === 'T') { V.travel = !V.travel; $('travel').checked = V.travel; }
    else return;
    $('lslider').value = V.layer; draw();
  });
  addEventListener('resize', () => M && draw());
})();
